import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { createResultReleaseRepository } from "./resultReleaseRepository.js";
const roots: string[] = [];
afterEach(() => { vi.restoreAllMocks(); roots.forEach(path => rmSync(path, { recursive: true, force: true })); });
const release = { projectId: 1, submissionId: 10, round: 1, fingerprint: "a".repeat(64), releasedBy: 3, releasedAt: "2026-11-12T12:00:00.000Z" };
it("persiste, restaura e conserva histórico com repetição idempotente", () => {
  const root = mkdtempSync(join(tmpdir(), "labrary-results-")); roots.push(root);
  const file = join(root, "private", "results.json");
  const repository = createResultReleaseRepository(file);
  expect(repository.find(1, release.fingerprint)).toBeUndefined();
  expect(repository.release(release)).toEqual(release);
  expect(repository.release({ ...release, releasedBy: 99 })).toEqual(release);
  const restored = createResultReleaseRepository(file);
  expect(restored.find(1, release.fingerprint)).toEqual(release);
  expect(restored.find(2, release.fingerprint)).toBeUndefined();
  restored.release({ ...release, round: 2, submissionId: 11, fingerprint: "b".repeat(64) });
  expect(JSON.parse(readFileSync(file, "utf8"))).toHaveLength(2);
  expect(statSync(file).mode & 0o777).toBe(0o600);
  expect(statSync(join(root, "private")).mode & 0o777).toBe(0o700);
  const copy = restored.find(1, release.fingerprint)!; copy.releasedBy = 99;
  expect(restored.find(1, release.fingerprint)!.releasedBy).toBe(3);
});
it("funciona em memória e falha sem descartar arquivo inválido ou erro de escrita", () => {
  const repository = createResultReleaseRepository();
  repository.release(release);
  expect(repository.find(1, release.fingerprint)).toEqual(release);
  expect(() => repository.release({ ...release, fingerprint: "inválido" })).toThrow();
  const root = mkdtempSync(join(tmpdir(), "labrary-results-")); roots.push(root);
  const file = join(root, "invalid.json"); writeFileSync(file, "não é JSON");
  expect(() => createResultReleaseRepository(file)).toThrow();
  expect(readFileSync(file, "utf8")).toBe("não é JSON");
  const invalid = createResultReleaseRepository(join(root, "missing.json"));
  rmSync(root, { recursive: true }); writeFileSync(root, "bloqueio");
  expect(() => invalid.release(release)).toThrow();
  expect(invalid.find(1, release.fingerprint)).toBeUndefined();
});
